def send_fcm_notification(alert_id, attack_type, severity):
    """
    Broadcasts a push notification payload out to Google's Firebase servers.
    Any Android device subscribed to the 'alerts' topic cluster will receive it.
    """
    try:
        message = messaging.Message(
            # Visible alert banner details displayed in the system tray
            notification=messaging.Notification(
                title=f"🚨 Critical Threat Detected: {attack_type}",
                body=f"Severity: {severity}. Tap to inspect full network metrics immediately."
            ),
            # Key-value data block processed by Android's NidsMessagingService
            data={
                "click_action": "FLUTTER_NOTIFICATION_CLICK",
                "deep_link_uri": f"nidsapp://alert/{alert_id}" # Read by Jetpack Compose NavHost
            },
            topic="alerts" # Broadcast target channel
        )
        # Relay the payload construction to Firebase Cloud Messaging api
        response = messaging.send(message)
        print(f"FCM notification dispatched successfully: {response}")
    except Exception as e:
        print(f"Failed to transmit message to FCM: {e}")
