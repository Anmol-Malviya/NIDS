# SIMULATE ATTACK
@api_bp.route("/api/simulate/<int:class_id>")
def simulate(class_id):
    result = simulate_attack(class_id)
    prediction_id = result["prediction"]
    attack_name = ATTACK_MAPPING[prediction_id]
    severity = get_severity(attack_name)
    src_ip = random_ip()
    dst_ip = random_ip()
    
    conn = get_db()
    
    # Execute the alert transaction record mapping
    cursor = conn.execute("""
    INSERT INTO alerts(
        attack_type,
        prediction,
        severity,
        src_ip,
        dst_ip,
        source_port,
        destination_port,
        protocol,
        flow_duration
    )
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        attack_name,
        prediction_id,
        severity,
        src_ip,
        dst_ip,
        result["source_port"],
        result["destination_port"],
        result["protocol"],
        result["flow_duration"]
    ))
    
    # =====================================================================
    # 🌟 NEW ADDITION: CAPTURE LAST ROW ID FOR THE DEEP LINK
    # =====================================================================
    # We must grab the exact autoincrement ID generated by SQLite for this row 
    # so we can push it within our URI string down to the phone.
    generated_id = cursor.lastrowid
    # =====================================================================
    
    conn.commit()
    conn.close()
    
    # =====================================================================
    # 🌟 NEW ADDITION: TRANSMIT POPUP ALERTS ON TRAFFIC SIMULATION
    # =====================================================================
    # Trigger the notification delivery block right after confirming the DB entry.
    # We wrap it to pass the fresh generated database index token smoothly.
    send_fcm_notification(generated_id, attack_name, severity)
    # =====================================================================

    return jsonify({
        "attack": attack_name,
        "severity": severity,
        "src_ip": src_ip,
        "dst_ip": dst_ip
    })


# GET ALERTS
@api_bp.route("/api/alerts")
def get_alerts():
    conn = get_db()
    alerts = conn.execute("""
    SELECT * FROM alerts
    ORDER BY timestamp DESC
    """).fetchall()
    conn.close()
    return jsonify([dict(row) for row in alerts])


# GET SINGLE ALERT
@api_bp.route("/api/alerts/<int:id>")
def get_alert(id):
    conn = get_db()
    alert = conn.execute("""
    SELECT * FROM alerts
    WHERE id=?
    """, (id,)).fetchone()
    conn.close()
    
    if alert is None:
        return jsonify({"error": "Not found"}), 404
        
    return jsonify(dict(alert))


