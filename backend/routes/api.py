# HEALTH
prev_packets_recv = psutil.net_io_counters().packets_recv
prev_packets_sent = psutil.net_io_counters().packets_sent
prev_time = time.time()

@api_bp.route("/api/health", methods=['GET'])
def health():
    global prev_packets_recv, prev_packets_sent, prev_time
    
    current_time = time.time()
    elapsed_time = current_time - prev_time if (current_time - prev_time) > 0 else 1
    io_counters = psutil.net_io_counters()
    
    # Calculate Rates
    pps_received = round((io_counters.packets_recv - prev_packets_recv) / elapsed_time, 1)
    pps_sent = round((io_counters.packets_sent - prev_packets_sent) / elapsed_time, 1)
    
    prev_packets_recv = io_counters.packets_recv
    prev_packets_sent = io_counters.packets_sent
    prev_time = current_time

    # Latency Check
    try:
        param = '-n' if os.name == 'nt' else '-c'
        command = ['ping', param, '1', '127.0.0.1']
        start_ping = time.time()
        output = subprocess.run(command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=1)
        latency = f"{round((time.time() - start_ping) * 1000, 1)} ms" if output.returncode == 0 else "TIMEOUT"
    except Exception:
        latency = "ERR"

    # Socket Inspection
    try:
        connections = psutil.net_connections(kind='inet')
        states = {"ESTABLISHED": 0, "SYN_RECV": 0, "TIME_WAIT": 0, "SYN_SENT": 0}
        for conn in connections:
            if conn.status in states:
                states[conn.status] += 1
    except Exception:
        states = {"ESTABLISHED": 0, "SYN_RECV": 0, "TIME_WAIT": 0, "SYN_SENT": 0}

    # DB Connection Check
    try:
        conn = get_db()
        conn.execute("SELECT 1")
        conn.close()
        db_status = "connected"
    except Exception:
        db_status = "error"

    # Return the structured payload matching your advanced monitor
    return jsonify({
        "cpu_percent": psutil.cpu_percent(interval=0.1),
        "memory_percent": psutil.virtual_memory().percent,
        "disk_percent": psutil.disk_usage('/').percent,
        "pps_in": pps_received,
        "pps_out": pps_sent,
        "mb_recv": round(io_counters.bytes_recv / (1024 * 1024), 2),
        "mb_sent": round(io_counters.bytes_sent / (1024 * 1024), 2),
        "latency": latency,
        "errors": io_counters.errin,
        "drops": io_counters.dropin,
        "established": states["ESTABLISHED"],
        "syn_recv": states["SYN_RECV"],
        "time_wait": states["TIME_WAIT"],
        "syn_sent": states["SYN_SENT"],
        "db_status": db_status
    })


